/* ------------------------------------------------------------------
   Files page: list the R2 bucket, upload to it, copy download links.

   Listing works in two modes:
     · portal API (Cloudflare Worker, see tools/r2-portal/worker.js) when
       site.Params.portalApi is set — also enables uploading and deleting;
     · otherwise a static files.json manifest generated by
       `python3 tools/r2_upload.py --manifest english-site/static/files.json`
       so links can still be copied without any backend.
 ------------------------------------------------------------------ */

(function () {
  var root = document.getElementById("portal");
  if (!root) return;

  // "none" is the placeholder Hugo renders when params.portalApi is empty
  var API = (root.dataset.api || "").trim();
  if (API === "none") API = "";
  API = API.replace(/\/+$/, "");
  var MANIFEST = root.dataset.manifest || "/files.json";
  var TOKEN_KEY = "ds-portal-token";

  var el = {
    status: document.getElementById("portal-status"),
    token: document.getElementById("portal-token"),
    tokenSave: document.getElementById("portal-token-save"),
    tokenClear: document.getElementById("portal-token-clear"),
    drop: document.getElementById("portal-drop"),
    file: document.getElementById("portal-file"),
    prefix: document.getElementById("portal-prefix"),
    progress: document.getElementById("portal-progress"),
    filter: document.getElementById("portal-filter"),
    refresh: document.getElementById("portal-refresh"),
    table: document.getElementById("portal-table"),
    rows: document.getElementById("portal-rows"),
    empty: document.getElementById("portal-empty"),
    count: document.getElementById("portal-count"),
    uploadCard: document.getElementById("portal-upload-card"),
  };

  var files = [];

  /* ---------- helpers ---------- */

  function token() {
    try { return localStorage.getItem(TOKEN_KEY) || ""; } catch (e) { return ""; }
  }

  function setToken(v) {
    try { v ? localStorage.setItem(TOKEN_KEY, v) : localStorage.removeItem(TOKEN_KEY); } catch (e) {}
    el.token.value = v;
    refresh();
  }

  function human(bytes) {
    if (!bytes && bytes !== 0) return "";
    var u = ["B", "KB", "MB", "GB"], i = 0, n = bytes;
    while (n >= 1024 && i < u.length - 1) { n /= 1024; i++; }
    return (i === 0 ? n : n.toFixed(n < 10 ? 1 : 0)) + " " + u[i];
  }

  function when(iso) {
    if (!iso) return "—";
    var d = new Date(iso);
    if (isNaN(d)) return "—";
    return d.toISOString().slice(0, 16).replace("T", " ") + "Z";
  }

  function baseName(key) {
    var parts = String(key).split("/");
    return parts[parts.length - 1];
  }

  function setStatus(text, kind) {
    el.status.textContent = text;
    el.status.className = "portal-note" + (kind ? " " + kind : "");
  }

  function copyText(text) {
    if (navigator.clipboard && navigator.clipboard.writeText) {
      return navigator.clipboard.writeText(text);
    }
    return new Promise(function (resolve, reject) {
      var ta = document.createElement("textarea");
      ta.value = text;
      ta.setAttribute("readonly", "");
      ta.style.position = "fixed";
      ta.style.top = "-1000px";
      document.body.appendChild(ta);
      ta.select();
      try { document.execCommand("copy") ? resolve() : reject(new Error("copy failed")); }
      catch (e) { reject(e); }
      document.body.removeChild(ta);
    });
  }

  function flash(btn, text) {
    var old = btn.textContent;
    btn.textContent = text;
    btn.disabled = true;
    setTimeout(function () { btn.textContent = old; btn.disabled = false; }, 1200);
  }

  /* ---------- rendering ---------- */

  function visibleFiles() {
    var q = (el.filter.value || "").trim().toLowerCase();
    if (!q) return files;
    return files.filter(function (f) { return f.key.toLowerCase().indexOf(q) !== -1; });
  }

  function render() {
    var shown = visibleFiles();
    el.rows.innerHTML = "";
    el.count.textContent = files.length ? "(" + files.length + ")" : "";
    el.empty.hidden = files.length > 0;
    el.table.hidden = files.length === 0;

    shown.forEach(function (f) {
      var tr = document.createElement("tr");

      var tdName = document.createElement("td");
      var a = document.createElement("a");
      a.href = f.url;
      a.textContent = f.key;
      a.title = f.key;
      tdName.appendChild(a);
      tr.appendChild(tdName);

      var tdSize = document.createElement("td");
      tdSize.className = "num";
      tdSize.textContent = human(f.size);
      tr.appendChild(tdSize);

      var tdWhen = document.createElement("td");
      tdWhen.className = "num";
      tdWhen.textContent = when(f.uploaded);
      tr.appendChild(tdWhen);

      var tdAct = document.createElement("td");
      tdAct.className = "right";

      var copy = document.createElement("button");
      copy.type = "button";
      copy.className = "portal-btn small";
      copy.textContent = "Copy link";
      copy.addEventListener("click", function () {
        copyText(f.url).then(function () { flash(copy, "Copied ✓"); },
                             function () { flash(copy, "Copy failed"); });
      });
      tdAct.appendChild(copy);

      var open = document.createElement("a");
      open.className = "portal-btn small ghost";
      open.href = f.url;
      open.target = "_blank";
      open.rel = "noopener";
      open.textContent = "Open";
      tdAct.appendChild(open);

      if (token()) {
        var del = document.createElement("button");
        del.type = "button";
        del.className = "portal-btn small danger";
        del.textContent = "Delete";
        del.addEventListener("click", function () {
          if (!confirm("Delete " + f.key + " from the bucket?")) return;
          del.disabled = true;
          api("POST", "/api/delete", { key: f.key }).then(function () {
            files = files.filter(function (x) { return x.key !== f.key; });
            render();
          }).catch(function (e) {
            alert("Delete failed: " + e.message);
            del.disabled = false;
          });
        });
        tdAct.appendChild(del);
      }
      tr.appendChild(tdAct);
      el.rows.appendChild(tr);
    });
  }

  /* ---------- talking to the worker ---------- */

  function api(method, path, body, extraHeaders) {
    var headers = { Authorization: "Bearer " + token() };
    var payload;
    if (body && !(body instanceof FormData)) {
      headers["content-type"] = "application/json";
      payload = JSON.stringify(body);
    } else {
      payload = body;
    }
    Object.assign(headers, extraHeaders || {});
    return fetch(API + path, { method: method, headers: headers, body: payload })
      .then(function (r) {
        return r.json().catch(function () { return {}; }).then(function (data) {
          if (!r.ok) throw new Error(data.error || ("HTTP " + r.status));
          return data;
        });
      });
  }

  function loadManifest() {
    return fetch(MANIFEST, { cache: "no-store" })
      .then(function (r) { if (!r.ok) throw new Error("HTTP " + r.status); return r.json(); })
      .then(function (data) { return (data && data.files) || []; })
      .catch(function () { return null; });
  }

  function refresh() {
    if (!API) {
      return loadManifest().then(function (list) {
        if (list) {
          files = list;
          render();
          setStatus("Upload backend not configured — showing the static file list. " +
                    "Uploads and deleting need the R2 portal Worker (see tools/r2-portal/).", "warn");
        } else {
          files = [];
          render();
          setStatus("No upload backend and no files.json manifest found.", "warn");
        }
      });
    }
    if (!token()) {
      return loadManifest().then(function (list) {
        files = list || [];
        render();
        setStatus("Portal token needed to upload or list live; showing the last generated list.",
                  "warn");
      });
    }
    setStatus("Loading the bucket…");
    return api("GET", "/api/list?limit=1000").then(function (data) {
      files = data.files || [];
      render();
      setStatus("Connected to the upload Worker — " + files.length + " file" +
                (files.length === 1 ? "" : "s") + " in the bucket.", "ok");
      if (el.uploadCard) el.uploadCard.classList.remove("disabled");
    }).catch(function (e) {
      setStatus("Portal request failed (" + e.message + ") — showing the static list instead.", "warn");
      return loadManifest().then(function (list) { files = list || []; render(); });
    });
  }

  /* ---------- uploading ---------- */

  function upload(fileList) {
    var list = Array.prototype.slice.call(fileList || []);
    if (!list.length) return;
    if (!API || !token()) {
      alert("Uploading needs the portal Worker and a token. See tools/r2-portal/README.md.");
      return;
    }
    list.forEach(function (f) {
      var li = document.createElement("li");
      li.textContent = f.name + " — waiting…";
      el.progress.appendChild(li);

      var form = new FormData();
      form.append("file", f);
      form.append("prefix", el.prefix.value || "uploads");

      var xhr = new XMLHttpRequest();
      xhr.open("POST", API + "/api/upload");
      xhr.setRequestHeader("Authorization", "Bearer " + token());
      xhr.upload.onprogress = function (e) {
        if (e.lengthComputable) {
          li.textContent = f.name + " — " + Math.round((e.loaded / e.total) * 100) + "%";
        }
      };
      xhr.onload = function () {
        var data = {};
        try { data = JSON.parse(xhr.responseText || "{}"); } catch (e) {}
        if (xhr.status >= 200 && xhr.status < 300 && data.files && data.files.length) {
          li.textContent = f.name + " — uploaded ✓";
          li.className = "ok";
        } else {
          li.textContent = f.name + " — failed: " + (data.error || ("HTTP " + xhr.status));
          li.className = "bad";
        }
        refresh();
      };
      xhr.onerror = function () { li.textContent = f.name + " — network error"; li.className = "bad"; };
      xhr.send(form);
    });
  }

  /* ---------- wiring ---------- */

  el.token.value = token();
  el.tokenSave.addEventListener("click", function () { setToken(el.token.value.trim()); });
  el.tokenClear.addEventListener("click", function () { setToken(""); });
  el.refresh.addEventListener("click", refresh);
  el.filter.addEventListener("input", render);

  el.drop.addEventListener("click", function () { el.file.click(); });
  el.drop.addEventListener("keydown", function (e) {
    if (e.key === "Enter" || e.key === " ") { e.preventDefault(); el.file.click(); }
  });
  el.file.addEventListener("change", function () { upload(el.file.files); el.file.value = ""; });
  ["dragenter", "dragover"].forEach(function (ev) {
    el.drop.addEventListener(ev, function (e) { e.preventDefault(); el.drop.classList.add("over"); });
  });
  ["dragleave", "drop"].forEach(function (ev) {
    el.drop.addEventListener(ev, function (e) { e.preventDefault(); el.drop.classList.remove("over"); });
  });
  el.drop.addEventListener("drop", function (e) {
    if (e.dataTransfer && e.dataTransfer.files) upload(e.dataTransfer.files);
  });

  refresh();
})();
